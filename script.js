function playPacMan(){
  let sound = document.getElementById("PacMan");
  if (sound.paused) {
    sound.play();
    document.getElementById("Pac").classList.add("gray");
  }
  else {
    sound.pause();
    document.getElementById("Pac").classList.remove("gray")
  }
}

